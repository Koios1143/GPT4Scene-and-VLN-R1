#!/usr/bin/env python3
"""SQA3D test + Real-3DQA -> GPT4Scene val annotations, appended to a config's ``val_file_dict``.

GPT4Scene releases SQA3D *val* only (``evaluate/annotation/sqa3d_val.json``, its paper's
split). This adds:

* ``sqa3d_test``: SQA3D test (3519 questions, 67 ScanNet val scenes, all with released images)
  from Chat-Scene's ``sqa3d_test.json`` (``--sqa3d_test``), whose prompt format is the one of
  GPT4Scene's ``sqa3d_val.json`` (``<situation> <question> Answer the question using a single
  word or phrase.``, identical prompts on the val split). ``qid`` = index in the file.
* ``real3dqa_<split>`` for ``debiased_test`` and ``rotation_{0,90,180,270}`` (HF
  Oliver-Ma/Real-3DQA ``<split>.jsonl``, ``--real3dqa_dir``), in the same SQA3D format:
  ``sqa_type`` = the question's first word (What/Is/How/Can/Which/other = 0..5),
  ``qid`` = Real-3DQA ``question_id``. The rotation splits differ only in the situation text,
  so the scene input (released frames + BEV) is the same as for SQA3D.

Writes ``<out_dir>/{sqa3d_test,real3dqa_<split>}.json`` and ``--config_out`` =
``--base_config`` plus their ``val_file_dict`` entries.
"""

import argparse
import json
import os

REAL3DQA_SPLITS = ["debiased_test", "rotation_0", "rotation_90", "rotation_180", "rotation_270"]
QA_SUFFIX = " Answer the question using a single word or phrase."
SQA_TYPE = {"what": 0, "is": 1, "how": 2, "can": 3, "which": 4}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sqa3d_test", required=True, help="Chat-Scene HF annotations/sqa3d_test.json")
    ap.add_argument("--real3dqa_dir", required=True, help="dir with Real-3DQA <split>.jsonl")
    ap.add_argument("--scene_anno", default="evaluate/annotation/selected_images_mark_3D_val_32.json")
    ap.add_argument("--base_config", required=True)
    ap.add_argument("--out_dir", required=True)
    ap.add_argument("--config_out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    have_images = set(json.load(open(args.scene_anno)))
    entries = {}

    annos = [dict(a, qid=i) for i, a in enumerate(json.load(open(args.sqa3d_test)))]
    entries["sqa3d_test"] = annos
    for split in REAL3DQA_SPLITS:
        out = []
        for line in open(os.path.join(args.real3dqa_dir, f"{split}.jsonl")):
            x = json.loads(line)
            q = x["question"].strip()
            out.append({"scene_id": x["scene_id"], "obj_id": 0,
                        "prompt": f'{x["situation"].strip()} {q}{QA_SUFFIX}',
                        "ref_captions": [x["answer"]],
                        "sqa_type": SQA_TYPE.get(q.split(" ")[0].lower(), 5),
                        "qid": int(x["question_id"]), "question_type": x["question_type"]})
        entries[f"real3dqa_{split}"] = out

    lines = ["\n\n# ---- SQA3D test / Real-3DQA (generated by extra_eval/build_annos.py) ----", "val_file_dict.update({"]
    for name, annos in entries.items():
        missing = sorted({a["scene_id"] for a in annos} - have_images)
        assert not missing, f"{name}: scenes without images {missing}"
        assert len({a["qid"] for a in annos}) == len(annos), f"{name}: duplicate qids"
        path = os.path.join(args.out_dir, f"{name}.json")
        json.dump(annos, open(path, "w"), indent=1)
        lines.append(f"    {name!r}: {path!r},")
        print(f"{name}: {len(annos)} questions, {len({a['scene_id'] for a in annos})} scenes -> {path}")
    lines.append("})\n")
    with open(args.config_out, "w") as f:
        f.write(open(args.base_config).read() + "\n".join(lines))
    print(f"config -> {args.config_out}")


if __name__ == "__main__":
    main()
